import puppeteer from 'puppeteer-core';
import { createServer } from 'node:http';
import { readFileSync, existsSync, mkdtempSync } from 'node:fs';
import { join, extname } from 'node:path';
import { tmpdir } from 'node:os';
const here = process.argv[2], variant = process.argv[3] || 'dark', out = process.argv[4];
const types = { '.html': 'text/html', '.js': 'text/javascript', '.jpg': 'image/jpeg' };
const srv = createServer((q, r) => { const f = join(here, q.url.split('?')[0] === '/' ? 'index.html' : q.url.split('?')[0]); if (!existsSync(f)) { r.writeHead(404); return r.end(); } r.writeHead(200, { 'content-type': types[extname(f)] || 'application/octet-stream' }); r.end(readFileSync(f)); });
await new Promise((r) => srv.listen(0, '127.0.0.1', r));
const chrome = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const b = await puppeteer.launch({ executablePath: existsSync(chrome) ? chrome : undefined, headless: true, userDataDir: mkdtempSync(join(tmpdir(), 'ink-')), args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--enable-webgl'] });
const p = await b.newPage();
await p.setViewport({ width: 1920, height: 1080 });
await p.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
await p.evaluateOnNewDocument((v) => { document.addEventListener('DOMContentLoaded', () => document.querySelector('[data-ink]').dataset.ink = v); }, variant);
p.on('console', (m) => console.log('console:', m.text()));
await p.goto(`http://127.0.0.1:${srv.address().port}/`);
await new Promise((r) => setTimeout(r, 12000));
console.log(await p.evaluate(() => JSON.stringify({ canvas: !!document.querySelector('canvas'), live: !!document.querySelector('.ink--live') })));
await p.screenshot({ path: out });
await b.close(); srv.close();
